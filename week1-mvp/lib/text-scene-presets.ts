/**
 * 文字场景预设 — scene-tools 和 batch-photo 共享
 *
 * 28 个预设与 scene_new_01..28 严格一一对应。
 *
 * 每段按"主体场景 + 关键物件 + 光线 + 调性"结构写，模型能：
 *   - 准确理解场景调性 + 色温
 *   - 按场景里的具体物件（桌 / 椅 / 门 / 楼梯 / 栏杆）自然互动
 *   - 主图导向：全身 / 大半身为主，避免局部细节
 */

export interface TextScenePreset {
  /** 短中文名（UI 下拉显示） */
  name: string;
  /** 完整场景描述（插入到文字场景输入框） */
  text: string;
  /** 调性分组（折叠显示用） */
  group: string;
  /**
   * 缩略图 URL。批量摄影中能匹配到 scenes 表时，也会作为参考图参与生成。
   */
  thumb?: string;
}

/**
 * scene_new_NN 文件扩展名映射（01 是 jpg，其他是 png）。
 * 28 张图都通过 migrateInsertNewScenesV3 拷到 DATA_DIR/uploads/scenes/，
 * 浏览器走 /assets/uploads/scenes/scene_new_NN.{jpg|png}。
 */
function thumbUrl(idx: number): string {
  const padded = String(idx).padStart(2, "0");
  const ext = idx === 1 ? "jpg" : "png";
  return `/assets/uploads/scenes/scene_new_${padded}.${ext}`;
}

